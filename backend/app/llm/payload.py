"""Compact JSON views the LLM receives (SPEC.md §6.6).

Every figure the model may mention is placed here, both as cents and as a
pre-formatted `*_display` string ("$1,000"), so the prompt can say "copy the
display string" and the guardrail (`guardrail.allowed_numbers`) sees the same
numbers the model does. Citations are never generated by the model: it returns
chunk ids and `citations_for()` turns them into `Citation` objects from the index.
"""
from __future__ import annotations

import re
from datetime import date
from typing import Any

from ..decisions.cache import Evaluation
from ..models import Citation, Constraint, Option, Profile, ProjectionResult, ScenarioTemplate

MAX_CHUNKS = 8
CHUNK_CHARS = 1600
BASELINE_LABEL = "No new coverage (baseline)"


def dollars(cents: int | None) -> str | None:
    if cents is None:
        return None
    sign = "-" if cents < 0 else ""
    c = abs(int(cents))
    return f"{sign}${c // 100:,}" if c % 100 == 0 else f"{sign}${c // 100:,}.{c % 100:02d}"


def inputs_view(inputs: Any) -> dict[str, Any]:
    data = inputs.model_dump(mode="json") if hasattr(inputs, "model_dump") else dict(inputs)
    return with_displays(data)


def with_displays(data: Any) -> Any:
    """Add a `*_display` string next to every `*_cents` integer, recursively (rent units are nested)."""
    if isinstance(data, list):
        return [with_displays(x) for x in data]
    if not isinstance(data, dict):
        return data
    out: dict[str, Any] = {}
    for k, v in data.items():
        out[k] = with_displays(v)
        if k.endswith("_cents") and isinstance(v, int):
            out[k[: -len("_cents")] + "_display"] = dollars(v)
    return out


def constraint_view(c: Constraint) -> dict[str, Any]:
    return {"id": c.id, "kind": c.kind, "rule": c.rule, "citation_ids": list(c.citation_ids), "applies_to": list(c.applies_to)}


def option_view(o: Option, constraints: list[Constraint]) -> dict[str, Any]:
    mine = [constraint_view(c) for c in constraints if c.id in o.constraint_ids]
    deductible = o.attributes.get("deductible")
    return {
        "id": o.id,
        "label": o.label,
        "attributes": dict(o.attributes),
        "deductible_display": dollars(int(deductible) * 100) if isinstance(deductible, int) and deductible else None,
        "price": {
            "monthly_cents": o.price.cents,
            "display": f"{dollars(o.price.cents)}/month",
            "kind": o.price.kind,
            "source": o.price.source_title,
        },
        "status": o.status,
        "constraints": mine,
    }


def _flag_view(f) -> dict[str, Any]:
    d = dict(f.detail)
    out: dict[str, Any] = {"code": f.code, "severity": f.severity, "month": f.month}
    for key in ("min_balance_cents", "deductible_cents", "unstressed_min_balance_cents", "monthly_slack_cents", "threshold_cents"):
        if key in d:
            out[key[: -len("_cents")] + "_display"] = dollars(d[key])
    for key in ("claim_date",):
        if key in d:
            out[key] = d[key]
    if "contributors" in d:
        out["contributors"] = [
            {"label": c.get("label"), "amount_display": dollars(c.get("amount_cents")), "date": c.get("date"), "kind": c.get("kind")}
            for c in d["contributors"]
        ]
    return out


def projection_view(p: ProjectionResult, *, series: bool = False) -> dict[str, Any]:
    out: dict[str, Any] = {
        "monthly_slack_display": dollars(p.monthly_slack_cents),
        "min_balance_display": dollars(p.min_balance_cents),
        "min_balance_date": p.min_balance_date.isoformat(),
        "months_below_floor": list(p.months_below_floor),
        "months_negative": list(p.months_negative),
        "flags": [_flag_view(f) for f in p.flags],
    }
    if series:
        out["months"] = [
            {"month": m.month, "end_balance_display": dollars(m.end_balance_cents), "min_balance_display": dollars(m.min_balance_cents)}
            for m in p.series
        ]
    return out


def module_view(module_id: str) -> dict[str, str]:
    from ..decisions import registry

    m = registry.get(module_id)
    return {"id": module_id, "title": getattr(m, "title", module_id), "description": getattr(m, "description", "")}


def option_labels(options: list[Option]) -> dict[str, str]:
    """id -> human label, plus the `baseline` key every projection map carries.

    The model is told to use these labels in prose; option ids only ever appear as JSON keys."""
    out = {o.id: o.label for o in options}
    out["baseline"] = BASELINE_LABEL
    return out


def projections_view(projections: dict[str, ProjectionResult], options: list[Option], *, series: bool = False) -> dict[str, dict[str, Any]]:
    """Per-option projection views, each carrying the option's `label` so the model never has to echo the id."""
    labels = option_labels(options)
    out: dict[str, dict[str, Any]] = {}
    for k, p in projections.items():
        view = {"label": labels.get(k, k)}
        view.update(projection_view(p, series=series))
        out[k] = view
    return out


_ID_CHARS = r"[A-Za-z0-9_]"


def replace_ids(text: str, labels: dict[str, str]) -> str:
    """Deterministic safety net: a raw id (option or scenario template) that leaked into prose
    becomes its label. Ids inside `[c:...]`/`[s:...]` markers are constraint and chunk ids, so
    the markers are left untouched."""
    if not text:
        return text
    for id_, label in sorted(labels.items(), key=lambda kv: -len(kv[0])):
        pattern = re.compile(rf"(?<!{_ID_CHARS})(?<!\[c:)(?<!\[s:)`?{re.escape(id_)}`?(?!{_ID_CHARS})")
        text = pattern.sub(label, text)
    return text


def replace_option_ids(text: str, options: list[Option]) -> str:
    return replace_ids(text, {o.id: o.label for o in options})


def scenario_labels(menu: list[ScenarioTemplate]) -> dict[str, str]:
    """template id -> human label; the model uses these in prose, ids only as JSON keys."""
    return {t.id: t.label for t in menu}


def replace_scenario_ids(text: str, menu: list[ScenarioTemplate]) -> str:
    return replace_ids(text, scenario_labels(menu))


def suggestions_view(ev: Evaluation) -> list[dict[str, Any]]:
    """Code-generated alternatives (big purchase: earliest safe date, safest financing) with `*_display`
    strings for every cents figure, so the model can restate them without converting anything."""
    labels = option_labels(ev.options)
    out: list[dict[str, Any]] = []
    for s in ev.suggestions:
        d = with_displays(s.model_dump(mode="json"))
        d["projected"]["option_label"] = labels.get(str(d["projected"].get("option_id")), d["projected"].get("option_id"))
        out.append(d)
    return out


def profile_view(profile: Profile) -> dict[str, Any]:
    return {
        "as_of": profile.as_of.isoformat(),
        "balance_display": dollars(profile.balance_cents),
        "safety_floor_display": dollars(profile.safety_floor_cents),
        "monthly_slack_display": dollars(profile.monthly_slack_cents),
        "income": [{"label": i.label, "amount_display": dollars(i.amount_cents), "cadence": i.cadence, "next_date": i.next_date.isoformat()} for i in profile.income],
        "recurring": [{"label": r.label, "amount_display": dollars(r.amount_cents), "cadence": r.cadence} for r in profile.recurring],
        "one_offs": [
            {"label": o.label, "amount_display": dollars(o.amount_cents), "date": o.date.isoformat()}
            for o in profile.one_offs
            if o.date >= profile.as_of
        ],
        "variable_spend": {"mean_monthly_display": dollars(profile.variable.mean_monthly_cents), "std_monthly_display": dollars(profile.variable.std_monthly_cents)},
    }


def retrieve_chunks(query: str, module_id: str, k: int = MAX_CHUNKS) -> list[dict[str, Any]]:
    """Top-k corpus chunks for the module as {id, title, publisher, text}. Empty if the index is unavailable."""
    try:
        from ..rag.retrieve import retrieve

        hits = retrieve(query, k=k, module=module_id)
    except Exception:  # index not built yet; the model then has nothing to cite and must not claim facts
        return []
    return [{"id": h.chunk.id, "title": h.chunk.title, "publisher": h.chunk.publisher, "text": h.chunk.text[:CHUNK_CHARS]} for h in hits]


def chunks_for_ids(chunk_ids: list[str]) -> list[dict[str, Any]]:
    """Chunks the constraints already cite, so the model can always ground the rules it names."""
    from ..rag.retrieve import get_chunk

    out = []
    for cid in dict.fromkeys(chunk_ids):
        c = get_chunk(cid)
        if c is not None:
            out.append({"id": c.id, "title": c.title, "publisher": c.publisher, "text": c.text[:CHUNK_CHARS]})
    return out


def merge_chunks(*groups: list[dict[str, Any]], limit: int = MAX_CHUNKS + 4) -> list[dict[str, Any]]:
    seen: set[str] = set()
    out: list[dict[str, Any]] = []
    for g in groups:
        for c in g:
            if c["id"] not in seen:
                seen.add(c["id"])
                out.append(c)
    return out[:limit]


def citations_for(chunk_ids: list[str], allowed_ids: set[str] | None = None) -> list[Citation]:
    """Citation objects for the chunk ids the model used; ids it was not given are dropped."""
    from ..rag.retrieve import citation_for

    out: list[Citation] = []
    for cid in dict.fromkeys(chunk_ids):
        if allowed_ids is not None and cid not in allowed_ids:
            continue
        c = citation_for(cid)
        if c is not None:
            out.append(c)
    return out


def evaluation_query(ev: Evaluation) -> str:
    """Retrieval query built from constraint rules + option attributes (SPEC §6.4 step 4)."""
    parts = [c.rule for c in ev.constraints]
    for o in ev.options:
        a = o.attributes
        parts.append(f"{o.label} {a.get('tort', '')} tort deductible {a.get('deductible', '')} collision comprehensive liability")
    return " ".join(parts)


def plan_months(profile: Profile, horizon: int = 12) -> dict[int, str]:
    """Plan month n (1 = first full month after as_of) -> 'YYYY-MM'."""
    y, m = profile.as_of.year, profile.as_of.month
    out: dict[int, str] = {}
    for n in range(1, horizon + 1):
        m += 1
        if m > 12:
            m, y = 1, y + 1
        out[n] = f"{y:04d}-{m:02d}"
    return out


def plan_month_start(profile: Profile, n: int) -> date:
    return date.fromisoformat(plan_months(profile)[n] + "-01")
